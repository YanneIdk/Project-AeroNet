let currentLang = 'zh';

function setLanguage(lang) {
  currentLang = translations[lang] ? lang : 'zh';
  const dict = translations[currentLang];
  document.documentElement.lang = currentLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });
}

function showWin7Dialog(titleKey, textKey) {
  const dict = translations[currentLang] || translations.zh;
  const overlay = document.getElementById("win7-dialog-overlay");
  const titleEl = document.getElementById("win7-dialog-title");
  const textEl = document.getElementById("win7-dialog-text");

  titleEl.textContent = dict[titleKey] || "国银提示";
  textEl.textContent = dict[textKey] || "Operation completed successfully.";
  overlay.classList.remove("hidden");
}

function hideWin7Dialog() {
  const overlay = document.getElementById("win7-dialog-overlay");
  overlay.classList.add("hidden");
}

document.addEventListener("DOMContentLoaded", () => {
  const switcher = document.getElementById("lang-switcher");
  if (switcher) {
    switcher.value = currentLang;
    setLanguage(currentLang);
    switcher.addEventListener("change", (e) => {
      setLanguage(e.target.value);
    });
  }

  // Glass Toggle Button Logic (Aero vs Classic) with only Chinese labels
  const glassToggleBtn = document.getElementById("glass-toggle-btn");
  const mainWindow = document.getElementById("main-window");
  if (glassToggleBtn && mainWindow) {
    glassToggleBtn.addEventListener("click", () => {
      mainWindow.classList.toggle("classic-mode");
      if (mainWindow.classList.contains("classic-mode")) {
        glassToggleBtn.textContent = "经典";
      } else {
        glassToggleBtn.textContent = "透明";
      }
    });
  }

  // Click Handlers for Interactive Links & Buttons
  const setupClickHandler = (id, titleKey, textKey) => {
    const el = document.getElementById(id);
    if (el) {
      el.addEventListener("click", (e) => {
        e.preventDefault();
        showWin7Dialog(titleKey, textKey);
      });
    }
  };

  setupClickHandler("nav-media-link", "popup_title_media", "popup_text_media");
  setupClickHandler("dl-brochure-btn", "popup_title_brochure", "popup_text_brochure");
  setupClickHandler("dl-player-btn", "popup_title_player", "popup_text_player");
  setupClickHandler("explore-btn", "popup_title_explore", "popup_text_explore");
  setupClickHandler("reports-btn", "popup_title_reports", "popup_text_reports");
  setupClickHandler("goals-btn", "popup_title_goals", "popup_text_goals");
  setupClickHandler("goal-carbon-btn", "popup_title_reports", "popup_text_reports");
  setupClickHandler("goal-water-btn", "popup_title_goals", "popup_text_goals");

  setupClickHandler("nav-solutions-link", "popup_title_explore", "popup_text_explore");
  setupClickHandler("nav-about-link", "popup_title_media", "popup_text_media");

  // Dialog close triggers
  document.getElementById("win7-dialog-close").addEventListener("click", hideWin7Dialog);
  document.getElementById("win7-dialog-ok").addEventListener("click", hideWin7Dialog);

  document.getElementById("win7-dialog-overlay").addEventListener("click", (e) => {
    if (e.target === e.currentTarget) {
      hideWin7Dialog();
    }
  });
});